#!/bin/bash
# shellcheck disable=SC2102
# Best-per-(model, dataset) HPs from best_model_reruns, re-run with stratified 5-fold CV.
# Uses seed=42 hyperparams as the canonical config when seed replicas differ slightly.
# W&B project: ogbench_kfold
# Aggregate with: aggregate_across_seeds(..., seed_col="dataset.split_params.data_seed", expected_seeds=5)
#
# Launch: bash scripts/rerun_best_kfold.sh
# Optional: MAX_PARALLEL=8 N_THREADS=2 bash scripts/rerun_best_kfold.sh

set -euo pipefail

ROOT_DIR="${ROOT_DIR:-/scratch/lcornelis/ogbench}"
WANDB_PROJECT="${WANDB_PROJECT:-ogbench_kfold}"
WANDB_ENTITY="${WANDB_ENTITY:-bioshape-lab}"
N_GPUS="${N_GPUS:-8}"
MAX_PARALLEL="${MAX_PARALLEL:-8}"
# Cap CPU threads per job (same as scripts/hyperparam_search.py) so parallel
# jobs do not oversubscribe OpenMP/MKL and thrash the machine / starve GPUs.
N_THREADS="${N_THREADS:-2}"

running=0

launch() {
  local gpu="$1"
  shift
  echo "[gpu ${gpu}] threads=${N_THREADS} $*"
  CUDA_VISIBLE_DEVICES="${gpu}" \
    OMP_NUM_THREADS="${N_THREADS}" \
    MKL_NUM_THREADS="${N_THREADS}" \
    OPENBLAS_NUM_THREADS="${N_THREADS}" \
    NUMEXPR_NUM_THREADS="${N_THREADS}" \
    TORCH_NUM_THREADS="${N_THREADS}" \
    "$@" &
  running=$((running + 1))
  if (( running >= MAX_PARALLEL )); then
    wait -n || true
    running=$((running - 1))
  fi
}


# chebnet / addneuromed / fold=0
launch 0 python -m ogbench \
    model=chebnet \
    dataset=addneuromed \
    experiment=omics_readout \
    dataset.loader.parameters.adjacency_method=wgcna \
    dataset.loader.parameters.node_sample_ratio=0.5 \
    dataset.loader.parameters.method=variance \
    optimizer.parameters.lr=0.0001 \
    optimizer.parameters.weight_decay=0.0 \
    model.backbone.dropout=0.1 \
    model.feature_encoder.out_channels=64 \
    model.backbone.num_layers=2 \
    dataset.loader.parameters.adjacency_threshold=0.202462 \
    model.readout.fc_dropout=0.1 \
    seed=42 \
    dataset.split_params.split_type=k-fold \
    dataset.split_params.k=5 \
    dataset.split_params.data_seed=0 \
    logger.wandb.tags=[chebnet,addneuromed,kfold,best_hp] \
    logger.wandb.entity="${WANDB_ENTITY}" \
    logger.wandb.project="${WANDB_PROJECT}" \
    paths.root_dir="${ROOT_DIR}" \
    trainer.devices=\[0\]

